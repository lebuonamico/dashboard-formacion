-- La app importa los 4 Excel, así que necesita SELECT + INSERT + UPDATE.
--
-- NO hay políticas de DELETE en ninguna tabla: nada se borra físicamente. Lo
-- que desaparece de un Excel se da de baja con UPDATE activo = false (borrado
-- lógico) en empleados y cursos, y por eso alcanza con permitir update.
--
-- Se incluye 'anon' porque el login de la app todavía no pasa por Supabase
-- Auth. Nunca usar service_role desde Flutter.
--
-- ⚠️ RIESGO CONOCIDO, A CERRAR ANTES DE CARGAR DATOS REALES ⚠️
-- Con 'anon' habilitado para escribir, cualquiera que tenga la publishable key
-- (viaja dentro de la app) puede leer y sobrescribir la nómina entera: legajos,
-- correos, gerentes y equipos. Cuando el login use Supabase Auth, borrar 'anon'
-- de las políticas de abajo y dejar solo 'authenticated'.

create policy "lectura importaciones" on importaciones
for select to anon, authenticated using (true);
create policy "carga importaciones" on importaciones
for insert to anon, authenticated with check (true);
create policy "actualiza importaciones" on importaciones
for update to anon, authenticated using (true) with check (true);

create policy "lectura empleados" on empleados
for select to anon, authenticated using (true);
create policy "carga empleados" on empleados
for insert to anon, authenticated with check (true);
create policy "actualiza empleados" on empleados
for update to anon, authenticated using (true) with check (true);

create policy "lectura cursos" on cursos
