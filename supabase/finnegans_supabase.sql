-- ------------------------------------------------------------
-- updated_at automático
-- ------------------------------------------------------------
create or replace function actualizar_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger trg_empleados_updated_at before update on empleados
for each row execute function actualizar_updated_at();

create trigger trg_cursos_updated_at before update on cursos
for each row execute function actualizar_updated_at();

create trigger trg_horas_updated_at before update on horas_capacitacion
for each row execute function actualizar_updated_at();

create trigger trg_estado_updated_at before update on estado_cursos
for each row execute function actualizar_updated_at();

